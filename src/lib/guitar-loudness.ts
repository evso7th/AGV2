export const GUITAR_LOUDNESS_TRIM_DB: Record<string, number> = {
    telecaster: 0,          // референс
    darkTelecaster: -11.90,
    blackAcoustic: -2.99,
    cs80: -4.17,
};

/** дБ → линейный коэффициент усиления. 0 дБ = 1.0 (без изменения). */
export const dbToGain = (db: number): number => Math.pow(10, db / 20);
