
#!/bin/bash

# Путь к манифесту и файлу для вывода
MANIFEST="public/audio-manifest.json"
LOST_ASSETS="lost_assets.txt"
PUBLIC_DIR="public"

# Проверяем, существует ли jq
if ! command -v jq &> /dev/null
then
    echo "Ошибка: утилита jq не установлена. Она необходима для обработки JSON."
    echo "Пожалуйста, установите jq и повторите попытку."
    exit 1
fi

# Очищаем или создаем файл для потерянных ассетов
> "$LOST_ASSETS"

# Читаем манифест, извлекаем каждый URL и проверяем его
# jq -r '.[]' извлекает каждый элемент из JSON-массива в виде "сырой" строки
jq -r '.[]' "$MANIFEST" | while IFS= read -r url; do
  # Формируем полный путь к файлу. URL в манифесте начинается с '/', 
  # поэтому мы соединяем 'public' и URL напрямую.
  file_path="${PUBLIC_DIR}${url}"
  
  # Проверяем, существует ли файл
  if [ ! -f "$file_path" ]; then
    # Если файла нет, добавляем его URL в список потерянных
    echo "$url" >> "$LOST_ASSETS"
  fi
done

# Проверяем, были ли найдены отсутствующие файлы
if [ -s "$LOST_ASSETS" ]; then
  echo "Найдены отсутствующие ассеты. Список сохранен в $LOST_ASSETS:"
  # Выводим содержимое файла для наглядности
  cat "$LOST_ASSETS"
else
  echo "Все ассеты на месте. Отсутствующие файлы не найдены."
  # Удаляем пустой файл
  rm "$LOST_ASSETS"
fi
